wait_for_job() {
  local jobid="$1"
  while true; do
    local remaining
    remaining="$(squeue -j "${jobid}" -h 2>/dev/null | wc -l | tr -d ' ')"
    if [[ "${remaining}" == "0" ]]; then
      break
    fi
    echo "[auto-saturn] job ${jobid}: ${remaining} array task(s) still queued/running; sleeping ${POLL_SECONDS}s"
    sleep "${POLL_SECONDS}"
  done
}

evaluate_target() {
  local analysis_dir="$1"
  local profile="$2"
  local jobid="$3"
  local eval_python="${PYTHON_BIN}"
  if [[ ! -x "${eval_python}" ]]; then
    eval_python="python3"
  fi
  "${eval_python}" - "${analysis_dir}" "${profile}" "${jobid}" "${SEED_LIST}" "${BUDGET}" "${SUMMARY_TSV}" <<'PY'
from __future__ import annotations

import csv
import json
import math
import os
import sys
from pathlib import Path

analysis_dir = Path(sys.argv[1])
profile = sys.argv[2]
jobid = sys.argv[3]
seed_list = sys.argv[4]
budget = sys.argv[5]
summary_tsv = Path(sys.argv[6])

seeds = [s.strip() for s in seed_list.replace(":", ",").replace(";", ",").split(",") if s.strip()]
n_seeds = max(1, len(seeds))

def target_float(name: str, default: float) -> float:
    raw = os.environ.get(name, "").strip()
    if not raw:
        return default
    if raw.lower() == "auto":
        return default
    return float(raw)

def target_success(name: str, default: int) -> int:
    raw = os.environ.get(name, "").strip()
    if not raw or raw.lower() == "auto":
        return default
    return int(float(raw))

targets = {
    "-9.0": {
        "success": target_success("TARGET_M9_SUCCESS", n_seeds),
        "yield": target_float("TARGET_M9_YIELD", 133.2),
        "modes": target_float("TARGET_M9_MODES", 76.3),
        "qed": target_float("TARGET_M9_QED", 0.82),
        "sa_max": target_float("TARGET_M9_SA_MAX", 2.79),
    },
    "-10.0": {
        "success": target_success("TARGET_M10_SUCCESS", max(1, math.ceil(0.7 * n_seeds))),
        "yield": target_float("TARGET_M10_YIELD", 6.5),
        "modes": target_float("TARGET_M10_MODES", 5.9),
        "qed": target_float("TARGET_M10_QED", 0.79),
        "sa_max": target_float("TARGET_M10_SA_MAX", 2.93),
    },
}

table_path = analysis_dir / "table8_spectralmol.tsv"
mol_path = analysis_dir / "all_molecules_standardized.tsv"
if not table_path.exists():
    raise SystemExit(f"Missing table output: {table_path}")

rows = {}
with table_path.open(newline="", encoding="utf-8") as table_handle:
    for row in csv.DictReader(table_handle, delimiter="\t"):
        rows[f"{float(row['threshold']):.1f}"] = row

def numeric(row, key, default=float("nan")):
    try:
        return float(row.get(key, ""))
    except Exception:
        return default

def integer(row, key, default=0):
    try:
        return int(float(row.get(key, "")))
    except Exception:
        return default

generated_hits = {"-9.0": 0, "-10.0": 0}
seed_hits = {"-9.0": 0, "-10.0": 0}
if mol_path.exists():
    with mol_path.open(newline="", encoding="utf-8") as mol_handle:
        for mol in csv.DictReader(mol_handle, delimiter="\t"):
            try:
                docking = float(mol.get("docking_raw", "nan"))
            except Exception:
                continue
            prefix = (mol.get("decode_reason") or "").split(":", 1)[0]
            origin = "seed" if prefix == "SEED_ENCODED" else "generated"
            for threshold in (-9.0, -10.0):
                if math.isfinite(docking) and docking < threshold:
                    key = f"{threshold:.1f}"
                    if origin == "seed":
                        seed_hits[key] += 1
                    else:
                        generated_hits[key] += 1

checks = []
flat = {
    "profile": profile,
    "jobid": jobid,
    "seed_list": seed_list,
    "budget": budget,
}
for threshold_key, target in targets.items():
    row = rows.get(threshold_key, {})
    prefix = "m9" if threshold_key == "-9.0" else "m10"
    success = integer(row, "successful_replicates")
    yld = numeric(row, "yield_mean")
    modes = numeric(row, "modes_mean")
    qed = numeric(row, "qed_mean")
    sa = numeric(row, "sa_mean")
    flat.update({
        f"{prefix}_success": success,
        f"{prefix}_yield": yld,
        f"{prefix}_modes": modes,
        f"{prefix}_qed": qed,
        f"{prefix}_sa": sa,
        f"{prefix}_generated_hits": generated_hits[threshold_key],
        f"{prefix}_seed_hits": seed_hits[threshold_key],
    })
    checks.extend([
        success >= target["success"],
        yld >= target["yield"],
        modes >= target["modes"],
        math.isfinite(qed) and qed >= target["qed"],
        math.isfinite(sa) and sa <= target["sa_max"],
    ])

passed = all(checks)
flat["passed"] = int(passed)

fields = [
    "profile", "jobid", "seed_list", "budget", "passed",
    "m9_success", "m9_yield", "m9_modes", "m9_qed", "m9_sa", "m9_generated_hits", "m9_seed_hits",
    "m10_success", "m10_yield", "m10_modes", "m10_qed", "m10_sa", "m10_generated_hits", "m10_seed_hits",
]
write_header = (not summary_tsv.exists()) or summary_tsv.stat().st_size == 0
summary_tsv.parent.mkdir(parents=True, exist_ok=True)
with summary_tsv.open("a", newline="", encoding="utf-8") as summary_handle:
    writer = csv.DictWriter(summary_handle, fieldnames=fields, delimiter="\t")
    if write_header:
        writer.writeheader()
    writer.writerow(flat)

(analysis_dir / "auto_target_status.json").write_text(json.dumps(flat, indent=2), encoding="utf-8")
print(json.dumps(flat, indent=2))
raise SystemExit(0 if passed else 1)
PY
}

main() {
  cd "${WORK_DIR}"
  if [[ ! -f "${SBATCH_SCRIPT}" ]]; then
    echo "[auto-saturn] Missing sbatch wrapper: ${SBATCH_SCRIPT}" >&2
    exit 2
  fi
  if [[ ! -f "${ANALYZER}" ]]; then
    echo "[auto-saturn] Missing analyzer: ${ANALYZER}" >&2
    exit 2
  fi

  local n
  n="$(seed_count)"
  if (( n <= 0 )); then
    echo "[auto-saturn] SEED_LIST is empty: ${SEED_LIST}" >&2
    exit 2
  fi
  local arr
  arr="$(array_spec "${n}")"

  echo "[auto-saturn] work_dir=${WORK_DIR}"
  echo "[auto-saturn] seed_list=${SEED_LIST} array=${arr} budget=${BUDGET}"
  echo "[auto-saturn] output_base=${OUTPUT_BASE}/${AUTO_RUN_ID}"
  echo "[auto-saturn] results_base=${RESULTS_BASE}"
  echo "[auto-saturn] profiles=${PROFILE_NAMES}"

  if [[ "${RESCORE_ONLY}" == "1" || "${RESCORE_ONLY}" == "true" || "${RESCORE_ONLY}" == "TRUE" ]]; then
    : > "${SUMMARY_TSV}"
    local any_rescored=0
    local any_matched=0
    local rescore_profile
    for rescore_profile in ${PROFILE_NAMES}; do
      local rescore_dir="${RESULTS_BASE}/${rescore_profile}"
      if [[ ! -f "${rescore_dir}/table8_spectralmol.tsv" ]]; then
        echo "[auto-saturn] rescore: missing ${rescore_dir}/table8_spectralmol.tsv; skipping"
        continue
      fi
      any_rescored=1
      if evaluate_target "${rescore_dir}" "${rescore_profile}" "rescored"; then
        any_matched=1
      fi
    done
    if (( any_rescored == 0 )); then
      echo "[auto-saturn] rescore: no completed analyses found under ${RESULTS_BASE}" >&2
      exit 2
    fi
    echo "[auto-saturn] rescore summary=${SUMMARY_TSV}"
    if (( any_matched == 1 )); then
      echo "[auto-saturn] TARGET MATCHED in existing analyses."
      exit 0
    fi
    echo "[auto-saturn] Existing analyses did not meet the target."
    exit 1
  fi

  local profile
  for profile in ${PROFILE_NAMES}; do
    apply_profile "${profile}"
    local output_root="${OUTPUT_BASE}/${AUTO_RUN_ID}/${profile}"
    local analysis_dir="${RESULTS_BASE}/${profile}"
    mkdir -p "${analysis_dir}"

    export SEED_LIST
    export PER_SEED_SEED_SMILES_DIR
    export BUDGET
    export OUTPUT_ROOT="${output_root}"

    echo "[auto-saturn] running profile=${profile} backend=${EXECUTION_BACKEND}"
    echo "[auto-saturn] output_root=${output_root}"
    local jobid
    if [[ "${EXECUTION_BACKEND}" == "local" ]]; then
      jobid="local-${profile}"
      local task_index
      for ((task_index = 0; task_index < n; task_index++)); do
        echo "[auto-saturn] local seed task ${task_index}/$((n - 1))"
        SLURM_ARRAY_TASK_ID="${task_index}" bash "${SBATCH_SCRIPT}"
      done
    elif [[ "${EXECUTION_BACKEND}" == "slurm" ]]; then
      command -v sbatch >/dev/null 2>&1 || {
        echo "[auto-saturn] sbatch not found; use EXECUTION_BACKEND=local." >&2
        exit 2
      }
      if [[ -n "${SBATCH_EXTRA_ARGS:-}" ]]; then
        echo "[auto-saturn] sbatch_extra_args=${SBATCH_EXTRA_ARGS}"
      fi
      jobid="$(sbatch ${SBATCH_EXTRA_ARGS:-} --array="${arr}" --export=ALL "${SBATCH_SCRIPT}" | awk '{print $4}')"
      echo "[auto-saturn] submitted job ${jobid}"
      wait_for_job "${jobid}"
    else
      echo "[auto-saturn] unknown EXECUTION_BACKEND=${EXECUTION_BACKEND}" >&2
      exit 2
    fi
    echo "[auto-saturn] job ${jobid} finished; analyzing"
    if ! "${PYTHON_BIN}" "${ANALYZER}" \
      --input-root "${output_root}" \
      --output-dir "${analysis_dir}" \
      --expected-seeds "${SEED_LIST}" \
      --budget "${BUDGET}"; then
      echo "[auto-saturn] analysis failed for profile=${profile}; continuing"
      continue
    fi

    if evaluate_target "${analysis_dir}" "${profile}" "${jobid}"; then
      echo "[auto-saturn] TARGET MATCHED by profile=${profile} job=${jobid}"
      echo "[auto-saturn] summary=${SUMMARY_TSV}"
      exit 0
    fi
    echo "[auto-saturn] target not met by profile=${profile}; continuing"
  done

  echo "[auto-saturn] No profile met the target."
  echo "[auto-saturn] summary=${SUMMARY_TSV}"
  exit 1
}

main "$@"
