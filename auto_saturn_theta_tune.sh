seed_count() {
  local raw="${SEED_LIST//:/,}"
  raw="${raw//;/,}"
  local old_ifs="${IFS}"
  IFS=','
  read -r -a seeds <<< "${raw}"
  IFS="${old_ifs}"
  local count=0
  for seed in "${seeds[@]}"; do
    seed="${seed//[[:space:]]/}"
    if [[ -n "${seed}" ]]; then
      count=$((count + 1))
    fi
  done
  printf '%s\n' "${count}"
}

array_spec() {
  local n="$1"
  local limit="${ARRAY_CONCURRENCY}"
  if [[ -z "${limit}" ]]; then
    limit="${n}"
  fi
  if (( n <= 1 )); then
    printf '0\n'
  else
    printf '0-%d%%%d\n' "$((n - 1))" "${limit}"
  fi
}

